"""Render docs/MODEL_CARDS.md from models/*/card.json so documented numbers always match the trained artefacts.

Usage: python scripts/gen_model_cards.py [--models models] [--out docs/MODEL_CARDS.md]
Metrics here are *cross-validation* metrics on the training data (grouped by task/conversation). Held-out test-split numbers
live in reports/EVAL_REPORT.md.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def fmt(v):
    if isinstance(v, float):
        return f"{v:.4f}"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {fmt(x)}" for k, x in list(v.items())[:12]) + ("…" if len(v) > 12 else "") + "}"
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v[:12]) + ("…" if len(v) > 12 else "") + "]"
    return str(v)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="models")
    ap.add_argument("--out", default="docs/MODEL_CARDS.md")
    a = ap.parse_args()
    root = Path(a.models)
    man = json.loads((root / "MANIFEST.json").read_text()) if (root / "MANIFEST.json").exists() else {}
    out = ["# Model cards", "",
           f"*Generated by `scripts/gen_model_cards.py` from `{a.models}/*/card.json` · bundle version {man.get('version')} · split `{man.get('split')}` · data hash `{str(man.get('data_hash'))[:12]}`*", "",
           "Metrics below are **cross-validation on training data** (grouped so a task/conversation never spans folds). Honest held-out numbers (tau2 test split, models trained on train only) are in `reports/EVAL_REPORT.md`. "
           "All models are CPU-only scikit-learn pipelines; none is a foundation model.", ""]
    for d in sorted(p for p in root.iterdir() if p.is_dir()):
        c = json.loads((d / "card.json").read_text()) if (d / "card.json").exists() else None
        if not c:
            continue
        out += [f"## {d.name}", ""]
        for k in ("cv", "n", "classes", "labels", "families", "applicable_issue_types", "dim", "trained_at"):
            if k in c:
                out.append(f"* **{k}**: {fmt(c[k])}")
        if c.get("metrics"):
            out += ["", "| metric | value |", "|---|---|"] + [f"| `{k}` | {fmt(v)} |" for k, v in c["metrics"].items()]
        if c.get("limitations"):
            out += ["", f"**Limitations.** {c['limitations']}"]
        out.append("")
    out += ["## Intended use", "Decision *support* and triage on telecom support transcripts; proposals are gated by a deterministic policy and human approval above limits. "
            "**Not** for automated decisions about customers without that gate, and not validated on real customer data, other languages (beyond English with light Hinglish/Spanglish code-switch handling), or audio.", ""]
    Path(a.out).write_text("\n".join(out))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
